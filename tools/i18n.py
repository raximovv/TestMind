def check():
    u"""Every language must define exactly the same keys.

    This is the whole reason the text lives in one file: a section that exists
    in Uzbek but was never translated should stop the build, not ship as a page
    that quietly says less than its siblings.
    """
    base = set(S['uz'])
    problems = []
    for lang in LANGS:
        missing, extra = base - set(S[lang]), set(S[lang]) - base
        for k in sorted(missing):
            problems.append('%s: missing %s' % (lang, k))
        for k in sorted(extra):
            problems.append('%s: unknown key %s' % (lang, k))
        for k in sorted(base & set(S[lang])):
            # An empty string is legitimate (uz has no "the test is in Uzbek"
            # note to make), but a key that is empty in *every* language is dead.
            if not isinstance(S[lang][k], type(u'')):
                problems.append('%s: %s is not text' % (lang, k))
    for k in sorted(base):
        if not any(S[lang][k].strip() for lang in LANGS):
            problems.append('key %s is empty in every language' % k)
    if problems:
        raise SystemExit('i18n.py:\n  ' + '\n  '.join(problems))
    return len(base)


if __name__ == '__main__':
    n = check()
    print('%d keys x %d languages = %d strings, all present'
          % (n, len(LANGS), n * len(LANGS)))
