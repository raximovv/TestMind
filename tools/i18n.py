u"""Every word of the static site, in Uzbek, Russian and English.

Why the text lives here and not in three copies of build_pages.py: the page
*structure* is identical in all three languages and only the prose differs. If
each language owned its own HTML, a section added to the Uzbek home page could
silently never appear in Russian. Here the template exists once and the
languages fill the same named slots, so a missing slot is a build error rather
than a page that quietly says less.

The test itself (test.html) is deliberately NOT translated. A translated
personality questionnaire is a different instrument that would need its own
validation, and mixing languages inside one dataset would make the responses
uninterpretable. The test stays Uzbek in all three versions of the site.

Register per language:
  uz  the students who actually take the test — plain, warm, second person
  ru  the same students in Russian-speaking families and schools
  en  not students. English exists for researchers, supervisors and partners,
      so it is allowed to be more precise about method and limitations.
"""

